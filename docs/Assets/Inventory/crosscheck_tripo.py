#!/usr/bin/env python3
"""Cross-check the inventory against docs/Assets/TripoAssetList.md (the earlier generated list, 1,285 assets).

Rows already covered by a chapter-derived asset (same normalised name or >= 0.6 token overlap) are skipped. The rest are appended
to that chapter's src file as [inferred] entries (the Tripo list is derived from the same story but names things the chapter text
does not state). Idempotent: the appended block is replaced on every run.
"""
import re, os, json, glob
HERE = os.path.dirname(os.path.abspath(__file__))
TRIPO = os.path.join(HERE, "..", "TripoAssetList.md")
BEGIN, END = "# --- TRIPO-CROSSCHECK-BEGIN (inferred; generated by crosscheck_tripo.py)\n", "# --- TRIPO-CROSSCHECK-END\n"
CAT = {"Main characters": "CHR", "Side characters / NPCs": "NPC", "Secrets": "CHR", "Enemies / creatures": "CRE", "Bosses": "CRE",
       "Weapons": "PRP", "Props / items": "PRP", "Vehicles": "VEH", "Environment pieces / buildings": "ARC", "Faction symbols": "PRP"}
SUB = {"Main characters": "Costume / outfit variant", "Side characters / NPCs": "NPC", "Secrets": "Secret outfit variant",
       "Enemies / creatures": "Enemy", "Bosses": "Boss", "Weapons": "Weapon", "Props / items": "Prop", "Vehicles": "Vehicle",
       "Environment pieces / buildings": "Set piece / modular kit", "Faction symbols": "Insignia"}
STOP = set("the a an of and to in on at for with".split())


def toks(s):
    s = re.sub(r"\[.*?\]|\(.*?\)", " ", s.lower())
    return {t for t in re.findall(r"[a-z0-9]+", s) if t not in STOP}


def norm(s):
    return " ".join(sorted(toks(s)))


def strip_blocks():
    for p in glob.glob(os.path.join(HERE, "src", "Ch[0-9][0-9].txt")):
        txt = open(p, encoding="utf-8").read()
        if BEGIN in txt:
            open(p, "w", encoding="utf-8").write(txt.split(BEGIN)[0].rstrip("\n") + "\n")


def main():
    strip_blocks()                      # match against chapter-derived assets only
    import importlib.util
    spec = importlib.util.spec_from_file_location("build_ledger", os.path.join(HERE, "build_ledger.py"))
    bl = importlib.util.module_from_spec(spec); spec.loader.exec_module(bl)
    import io, contextlib
    with contextlib.redirect_stdout(io.StringIO()):
        bl.rebuild_all()
    reg = json.load(open(os.path.join(HERE, "registry.json")))
    names = [(toks(a["name"]), norm(a["name"])) for a in reg["assets"].values()]
    meta = [(toks(a["name"]), a["id"], a["name"]) for a in reg["assets"].values()]
    exact = {n for _, n in names}
    rows, sec = [], None
    for l in open(TRIPO, encoding="utf-8"):
        if l.startswith("## "):
            sec = l[3:].strip()
            continue
        m = re.match(r"^\| (\d+) \| (.*?) \| Ch (\d+) \| (.*?) \| (.*?) \| (.*)\|\s*$", l)
        if m and sec in CAT:
            rows.append((int(m.group(1)), sec, re.sub(r"\s*\[IMPLIED\]", "", m.group(2)).strip(), int(m.group(3)), m.group(4).strip()))
    out, kept = {}, 0
    for n, sec, name, ch, desc in rows:
        t = toks(name)
        if not t:
            continue
        if norm(name) in exact:
            continue
        best = max((len(t & nt) / max(1, len(t | nt)) for nt, _ in names), default=0)
        contained = any(t <= nt or nt <= t for nt, _ in names if len(t) >= 2 and len(nt) >= 2)
        note = "not named in the chapter text"
        if best >= 0.6 or (contained and best >= 0.5):
            # near-match: still listed so every Tripo row exists as an entry; the likely twin is named for the merge decision
            cand = max(meta, key=lambda m: len(t & m[0]) / max(1, len(t | m[0])))
            note = "likely the same asset as %s %s; kept as its own entry so no Tripo row is dropped" % (cand[1], cand[2])
        d = "%s [inferred: Tripo list #%d; %s]" % (desc.replace("|", "/"), n, note)
        out.setdefault(ch, []).append("%s|%s|%s|Tripo #%d|B|%s|" % (CAT[sec], name.replace("|", "/"), SUB[sec], n, d))
        kept += 1
    for p in glob.glob(os.path.join(HERE, "src", "Ch[0-9][0-9].txt")):
        ch = int(os.path.basename(p)[2:4])
        txt = open(p, encoding="utf-8").read()
        if BEGIN in txt:
            txt = txt.split(BEGIN)[0]
        if ch in out:
            txt = txt.rstrip("\n") + "\n" + BEGIN + "\n".join(out[ch]) + "\n" + END
        open(p, "w", encoding="utf-8").write(txt)
    print("tripo rows %d, added %d, per chapter %s" % (len(rows), kept, {k: len(v) for k, v in sorted(out.items())}))


main()

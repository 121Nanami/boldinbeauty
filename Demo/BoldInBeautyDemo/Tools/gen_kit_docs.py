#!/usr/bin/env python3
"""Regenerates docs/operator-kits.md from the kit data (BIBRules/BIBKit*.cpp) and the balance simulator.

The kit tables come from Tests/dump_kits.cpp (one JSON document) and the balance table from Tests/kit_balance.cpp, so the
document can never drift from the code. Usage: python3 Tools/gen_kit_docs.py   (needs a C++20 compiler; CXX overrides c++)
"""
import json
import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(ROOT))
RULES = os.path.join(ROOT, 'Source', 'BoldInBeautyDemo', 'BIBRules')
OUT = os.path.join(REPO, 'docs', 'operator-kits.md')
SOURCES = ['BIBKitStatus', 'BIBKitRegistry', 'BIBKitRuntime', 'BIBKitSteps', 'BIBKitCombat', 'BIBKitHooks',
           'BIBKitData1', 'BIBKitData2', 'BIBKitData3', 'BIBCore', 'BIBCampaign', 'BIBMeta', 'BIBMetaOps', 'BIBPages', 'BIBTutorial', 'BIBTester',
           'BIBJson', 'BIBSave', 'BIBArcade', 'BIBArena', 'BIBLiveOps', 'BIBOnline', 'BIBPagesExtra', 'BIBSynth', 'BIBMiniGames', 'BIBElement', 'BIBInventory', 'BIBEvents', 'BIBPagesGacha']
SOURCE_LABEL = {0: 'PLACEHOLDER', 1: 'SOURCE (owner)', 2: 'PROPOSED'}
KEYS = {'M1': 'LMB', 'Move1': '1', 'Move2': '2', 'Move3': '3', 'Special': '4', 'Ultimate': 'E'}

def build(test, name):
    exe = os.path.join(tempfile.gettempdir(), name)
    cmd = [os.environ.get('CXX', 'c++'), '-std=c++20', '-O2', '-fno-exceptions', '-fno-rtti',
           os.path.join(ROOT, 'Tests', test)] + [os.path.join(RULES, s + '.cpp') for s in SOURCES] + ['-o', exe]
    subprocess.run(cmd, check=True)
    return subprocess.run([exe], check=True, capture_output=True, text=True).stdout

def cell(text):
    return text.replace('|', '/').replace('\n', ' ')

def fmt_cd(ability):
    if ability['slot'] == 'M1':
        return '%.2f s' % ability['cooldown']
    if ability['cooldown'] <= 0:
        return 'ult bar'
    return '%g s' % ability['cooldown']

def main():
    kits = json.loads(build('dump_kits.cpp', 'bib_dump_kits'))['kits']
    balance = build('kit_balance.cpp', 'bib_kit_balance').rstrip()
    lines = []
    w = lines.append
    w('# Operator kits - demo implementation')
    w('')
    w('*Generated by `Demo/BoldInBeautyDemo/Tools/gen_kit_docs.py` from the kit data; do not edit by hand.*')
    w('')
    w('Every operator has a regular attack (M1), three standard moves, one independent Special and one Ultimate (MAIN section 6). Only 5-6 star operators have')
    w('passives (1-4); 3-4 star operators have none. Luna, Judge and Narrator are written by hand in Unreal (`BIBKitLuna/Judge/Narrator.cpp`, owner files);')
    w('the 17 operators below are data (`BIBRules/BIBKitData*.cpp`) run by `BIB::Kits::FRuntime`.')
    w('')
    w('Source labels: **SOURCE (owner)** = written by the owner (Notion operator pages); **PROPOSED** = designed by the assistant on 2026-10-04 from the')
    w("owner's playstyle notes (owner decides: keep, change or reject); **PLACEHOLDER** = a value the demo needs that the owner has not decided.")
    w('Cooldowns, damage numbers, radii and durations of PROPOSED and PLACEHOLDER entries are balance starting points, not decisions.')
    w('')
    w('## Balance reference')
    w('')
    w('Simulated with `Tests/kit_balance.cpp` (`Tests/run_core_tests.sh --balance`). Relative scale only: no incoming damage, stationary dummies, perfect rotation.')
    w('')
    w('```text')
    w(balance)
    w('```')
    w('')
    for kit in kits:
        w('## %s - %d-star' % (kit['name'], kit['stars']))
        w('')
        w('*%s*' % kit['playstyle'])
        w('')
        res = ', '.join('%s (max %g, start %g%s)' % (r['name'], r['max'], r['start'], (', %+g/s' % r['regen']) if r['regen'] else '') for r in kit['resources']) or 'none'
        traits = []
        if kit['damageTaken']:
            traits.append('damage taken %+d%%' % round(kit['damageTaken'] * 100))
        if kit['statusResist']:
            traits.append('%d%% status resist' % round(kit['statusResist'] * 100))
        if kit['shield']:
            traits.append('starts with %g shield' % kit['shield'])
        if not kit['canSprint']:
            traits.append('cannot sprint')
        if kit['specialOnR']:
            traits.append('Special is on R')
        w('- Stats (PLACEHOLDER unless owner-written): HP %g, regular attack %g, walk x%g, run x%g, jump x%g, dodge cooldown %g s%s' % (
            kit['hp'], kit['attack'], kit['walk'], kit['run'], kit['jump'], kit['dodgeCooldown'], ('; ' + ', '.join(traits)) if traits else ''))
        w('- Resources: %s' % res)
        w('- Gameplay tags: `BIB.Kit.%s`, `BIB.Ability.<id>`, `BIB.Cooldown.<id>`, `BIB.Passive.<id>`' % kit['name'])
        w('')
        w('| Slot | Key | Ability | Cooldown | Source | What it does | Tags |')
        w('|---|---|---|---|---|---|---|')
        for a in kit['abilities']:
            slot = a['slot']
            key = 'R' if (slot == 'Special' and kit['specialOnR']) else KEYS.get(slot, '?')
            name = a['name'] + ((' (%s)' % a['cast']) if a['cast'] != 'instant' else '')
            w('| %s | %s | %s | %s | %s | %s | %s |' % (slot, key, cell(name), fmt_cd(a), SOURCE_LABEL.get(a['source'], '?'), cell(a['note']),
                ' '.join('`%s`' % t for t in a['tags'])))
        if kit['passives']:
            w('')
            w('| Passive | Trigger | Source | What it does |')
            w('|---|---|---|---|')
            for p in kit['passives']:
                w('| %s | %s | %s | %s |' % (cell(p['name']), p['trigger'], SOURCE_LABEL.get(p['source'], '?'), cell(p['note'])))
        w('')
    with open(OUT, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines) + '\n')
    print('wrote', OUT, '(%d lines)' % len(lines))

if __name__ == '__main__':
    main()

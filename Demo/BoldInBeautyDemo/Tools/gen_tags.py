#!/usr/bin/env python3
"""Regenerates the BIB.* / GameplayCue.BIB.* gameplay tags in Config/DefaultGameplayTags.ini.

The tags come from the kit data (BIBRules/BIBKit*.cpp) through Tests/dump_tags.cpp, so the tag list can never drift from
the code. Tags that are not BIB.* / GameplayCue.BIB.* (anything the owner adds in the editor) are preserved.
Usage: python3 Tools/gen_tags.py        (needs a C++20 compiler; CXX overrides c++)
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RULES = os.path.join(ROOT, 'Source', 'BoldInBeautyDemo', 'BIBRules')
INI = os.path.join(ROOT, 'Config', 'DefaultGameplayTags.ini')
SECTION = '[/Script/GameplayTags.GameplayTagsSettings]'

def build_and_dump():
    sources = ['BIBKitStatus', 'BIBKitRegistry', 'BIBKitRuntime', 'BIBKitSteps', 'BIBKitCombat', 'BIBKitHooks',
               'BIBKitData1', 'BIBKitData2', 'BIBKitData3', 'BIBCore', 'BIBCampaign', 'BIBMeta', 'BIBMetaOps', 'BIBPages', 'BIBTutorial', 'BIBTester',
               'BIBJson', 'BIBSave', 'BIBArcade', 'BIBArena', 'BIBLiveOps', 'BIBOnline', 'BIBPagesExtra', 'BIBSynth', 'BIBMiniGames', 'BIBElement', 'BIBInventory', 'BIBEvents', 'BIBPagesGacha']
    exe = os.path.join(tempfile.gettempdir(), 'bib_dump_tags')
    cmd = [os.environ.get('CXX', 'c++'), '-std=c++20', '-O1', '-fno-exceptions', '-fno-rtti',
           os.path.join(ROOT, 'Tests', 'dump_tags.cpp')] + [os.path.join(RULES, s + '.cpp') for s in sources] + ['-o', exe]
    subprocess.run(cmd, check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    return [line.strip() for line in out.splitlines() if line.strip()]

def is_ours(tag):
    return tag.startswith('BIB.') or tag == 'BIB' or tag.startswith('GameplayCue.BIB.')

def main():
    tags = build_and_dump()
    kept = []
    other_sections = []
    if os.path.exists(INI):
        current = None
        for line in open(INI, encoding='utf-8').read().splitlines():
            if line.startswith('['):
                current = line.strip()
                if current != SECTION:
                    other_sections.append(line)
                continue
            if current == SECTION:
                m = re.match(r'\+GameplayTagList=\(Tag="([^"]+)"', line)
                if m and not is_ours(m.group(1)):
                    kept.append(line)
            elif current is not None:
                other_sections.append(line)
    lines = [SECTION, '; Generated by Tools/gen_tags.py from the operator kit data. Do not edit the BIB.* lines by hand.']
    lines += kept
    for tag in sorted(set(tags)):
        lines.append('+GameplayTagList=(Tag="%s",DevComment="Boldinbeauty demo")' % tag)
    if other_sections:
        lines.append('')
        lines += other_sections
    os.makedirs(os.path.dirname(INI), exist_ok=True)
    open(INI, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %d tags to %s' % (len(set(tags)), INI))

if __name__ == '__main__':
    sys.exit(main())

// Generator for the campaign tables. Built by Tools/gen_campaign_data.py with -DBIB_CAMPAIGN_BOOTSTRAP (BIBCampaign.cpp then does
// not read the tables it is about to produce).
//   dump_campaign --inc   prints BIBRules/BIBCampaignData.inc
//   dump_campaign --md    prints docs/campaign.md
#include "campaign_model.h"

#include <cstdio>
#include <cstring>
#include <string>

namespace
{
	using namespace CampaignModel;

	void PrintInc(const FSolved& Solved)
	{
		std::printf("// GENERATED by Tools/gen_campaign_data.py from Tests/campaign_model.h. Do not edit by hand: change a constant in\n");
		std::printf("// the model or in BIBCampaign.h, rerun the tool, run Tests/run_core_tests.sh (campaign_tests checks this file is current).\n");
		std::printf("// Included inside namespace BIB::Campaign by BIBCampaign.cpp.\n");
		std::printf("namespace Data\n{\n");
		std::printf("\t// Enemies per section (mini-boss and boss sections included) of chapters 2..13, levels 1..8.\n");
		std::printf("\tconstexpr int SectionSize[12][8] = {\n");
		for (int Chapter = FirstGeneratedChapter; Chapter <= CampaignChapters; ++Chapter)
		{
			std::printf("\t\t{");
			for (int Level = 1; Level <= CampaignLevels; ++Level)
			{
				const size_t Index = static_cast<size_t>((Chapter - FirstGeneratedChapter) * CampaignLevels + (Level - 1));
				std::printf("%d%s", Solved.Sizes[Index].Size, Level < CampaignLevels ? ", " : "");
			}
			std::printf("},%s\n", Chapter == FirstGeneratedChapter ? "   // chapter 2 (row 0) ... chapter 13 (row 11)" : "");
		}
		std::printf("\t};\n");
		auto PrintDoubles = [&Solved](const char* Name, const char* Comment, bool bHp)
		{
			std::printf("\t// %s\n\tconstexpr double %s[%d] = {", Comment, Name, TotalCampaignLevels);
			for (int Stage = 1; Stage <= TotalCampaignLevels; ++Stage)
			{
				const FEnemyScale& Scale = Solved.Tables.Scale[static_cast<size_t>(Stage)];
				std::printf("%s%s%.9g", (Stage - 1) % 8 == 0 ? "\n\t\t" : "", Stage % 8 == 1 ? "" : " ", bHp ? Scale.Hp : Scale.Damage);
				std::printf("%s", Stage < TotalCampaignLevels ? "," : "");
			}
			std::printf("\n\t};\n");
		};
		PrintDoubles("HpScale", "Enemy health multiplier by stage id - 1 (every chapter, Chapter 1 included, solved from the reference player).", true);
		PrintDoubles("DamageScale", "Enemy damage multiplier by stage id - 1.", false);
		std::printf("\t// Recommended average team level by stage id - 1.\n\tconstexpr int Recommended[%d] = {", TotalCampaignLevels);
		for (int Stage = 1; Stage <= TotalCampaignLevels; ++Stage)
		{
			std::printf("%s%s%d%s", (Stage - 1) % 8 == 0 ? "\n\t\t" : "", Stage % 8 == 1 ? "" : " ",
				Solved.Tables.Recommended[static_cast<size_t>(Stage)], Stage < TotalCampaignLevels ? "," : "");
		}
		std::printf("\n\t};\n}\n");
	}

	void PrintMarkdown(const FSolved& Solved)
	{
		const FThreatContext Context = MakeThreatContext(Solved.Tables);
		std::printf("# Campaign: 13 chapters of standard enemies, balanced to the economy\n\n");
		std::printf("*Generated by `Tools/gen_campaign_data.py` from `Tests/campaign_model.h`. Do not edit by hand. Every number is a **PLACEHOLDER**\n");
		std::printf("(MAIN leaves enemy stats, level counts per chapter, rewards and rates OPEN or DEFERRED); the owner replaces them.*\n\n");
		std::printf("Owner request, 2026-10-05: fill chapters 2-13 with levels made of standard balancing enemies, a mini boss at the end of every\n");
		std::printf("level (in a chapter's last level, the mini boss in the section before the boss), and balance each stage to the currency,\n");
		std::printf("levels and operators a player has at that point, a bit harder so that some grinding is needed.\n\n");
		std::printf("## What was built\n\n");
		std::printf("Owner rebalance, 2026-10-06: a much heavier health and damage increase per operator level (+%.0f%% per level, was +1%%) with the\n", Config::StatPercentPerLevel);
		std::printf("enemies scaled to match (Chapter 1 included); stage rewards start at 800 Gold, 250 Bytes and 2 Angel hearts per clear and 50 Diamonds on the\n");
		std::printf("first clear; a new account starts with 300 Diamonds and nothing else; tickets come from the story quests.\n\n");
		std::printf("- **13 chapters x 8 levels** (Chapter 1 keeps its original eight level layouts; the other twelve follow it, PLACEHOLDER). Levels unlock in order,\n");
		std::printf("  chapters unlock when the previous chapter's boss is cleared; the admin account has every level open.\n");
		std::printf("- **Every level** has 2-5 sections of 10-30 enemies (MAIN section 7) and ends with **one mini boss**. A **chapter's last level** has\n");
		std::printf("  five sections: the mini boss closes section 4, the **chapter boss** closes section 5 (so the mini boss is the stage before the boss).\n");
		std::printf("- **Seven enemy archetypes**: basic (melee), ranged, mage (area blasts), brute (tank), assassin (high damage, close range, low\n");
		std::printf("  health), mini boss, boss. They appear chapter by chapter: ranged in 2, mages in 3, assassins in 4; from chapter 5 every chapter leans\n");
		std::printf("  on one or two of them (a PLACEHOLDER mix, no lore).\n");
		std::printf("- **Balance**: a reference player (below) fixes how many levels, upgrade stars and operators a player has at each stage; the enemy\n");
		std::printf("  health and damage scale from there and each stage is made a bit harder than that player's pace, so about one replay of an earlier\n");
		std::printf("  stage is needed per level and two or three before a boss.\n\n");

		std::printf("## Enemy archetypes (base numbers, multiplied by the stage's scales)\n\n");
		std::printf("| Archetype | Health | Damage | Every | Telegraph | Speed | Reach | Notes |\n|---|---:|---:|---:|---:|---:|---:|---|\n");
		for (int Index = 0; Index < ArchetypeCount; ++Index)
		{
			const FArchetype& A = Archetype(static_cast<EArchetype>(Index));
			std::string Reach = A.Range > 0.0 ? std::to_string(static_cast<int>(A.Range)) + " cm" : "melee";
			std::string Notes = A.Role;
			if (A.AoeRadius > 0.0)
			{
				Notes += " Blast radius " + std::to_string(static_cast<int>(A.AoeRadius)) + " cm.";
			}
			if (A.SlamDamage > 0.0)
			{
				Notes += " Slam " + std::to_string(static_cast<int>(A.SlamDamage)) + " every " + std::to_string(static_cast<int>(A.SlamInterval)) + " s, radius " + std::to_string(static_cast<int>(A.SlamRadius)) + " cm.";
			}
			std::printf("| %s | %d | %d | %.1f s | %.1f s | %d | %s | %s |\n", A.Name, static_cast<int>(A.Hp), static_cast<int>(A.Damage), A.Interval, A.Windup,
				static_cast<int>(A.Speed), Reach.c_str(), Notes.c_str());
		}

		std::printf("\n## The reference player\n\n");
		std::printf("A player who clears the stages in order, spends everything on a team of three operators (all at the same level), and replays the newest\n");
		std::printf("stage when the next one asks for more levels than they have. Assumptions, all PLACEHOLDER:\n\n");
		std::printf("- Income: `StageReward` (BIBCampaign.h), paid on every clear: Gold %d, Bytes %d and Angel hearts %d at stage 1, Gold and Bytes growing by %.0f%%\n",
			RewardGoldBase, RewardBytesBase, RewardHeartsBase, RewardGrowthPerStage * 100.0);
		std::printf("  of that per stage, hearts by %.0f%%\n", RewardHeartsGrowthPerStage * 100.0);
		std::printf("  per stage (stage 103: Gold %d, Bytes %d, hearts %d); a boss level pays x%.0f. Diamonds on the first clear only: %d in Chapter 1, +%d per chapter,\n",
			StageReward(TotalCampaignLevels - 1).Gold, StageReward(TotalCampaignLevels - 1).Bytes, StageReward(TotalCampaignLevels - 1).Hearts,
			RewardBossMultiplier, RewardDiamondsBase, RewardDiamondsPerChapter);
		std::printf("  x%d on a boss level. Story quests (BIBMetaOps.h) add 20-50 Diamonds after level 3, Gold and Bytes or Angel hearts after level 6, and the\n",
			RewardBossDiamondsMultiplier);
		std::printf("  chapter's Regular tickets (10 for Chapter 1, 1 after that) at its end. Daily and weekly quests are left out of the model (bonus income).\n");
		std::printf("- Costs: the real rules (`LevelUpCost`, `HeartGateCost`, level cap 100 + 20 per upgrade star); %.0f%% of the currency reaches the three\n", SpendEfficiency * 100.0);
		std::printf("  team operators (the rest goes to equipment and other operators).\n");
		std::printf("- Operators: every pull (Diamonds / %d, plus the story-quest tickets) can duplicate a team member; duplicates give upgrade stars (5%% damage\n", Config::DiamondsPerRoll);
		std::printf("  and defence each); equipment adds up to %.0f%%; a bigger roster adds up to %.0f%% (better team choice). Expected summons by the last stage: %.0f.\n",
			EquipmentMaxPercent, RosterBonusMax * 100.0, Solved.Tables.Pace[static_cast<size_t>(TotalCampaignLevels)].Pulls);
		std::printf("- \"A bit harder\": a stage asks for the team level the player would have after %.1f more clears of the newest stage (%.1f before a chapter boss,\n",
			ReplaysNormal, ReplaysChapterEnd);
		std::printf("  chapter 2 eases in from %.0f%% of that). That is the grind.\n", ReplayRampStart * 100.0);
		int TotalReplays = 0;
		for (int Stage = 1; Stage <= TotalCampaignLevels; ++Stage)
		{
			TotalReplays += Solved.Tables.Pace[static_cast<size_t>(Stage)].Replays;
		}
		std::printf("- Result: the reference player needs **%d replays over the %d stages** (%.1f clears per stage), and reaches team level %d at the last stage\n",
			TotalReplays, TotalCampaignLevels, static_cast<double>(TotalCampaignLevels + TotalReplays) / TotalCampaignLevels,
			Solved.Tables.Recommended[static_cast<size_t>(TotalCampaignLevels)]);
		std::printf("  with %d upgrade stars. The base level cap is %d and each upgrade star (a duplicate summon) adds %d, so the last chapters need duplicates of\n",
			Solved.Tables.Pace[static_cast<size_t>(TotalCampaignLevels)].Stars, Config::BaseLevelCap, Config::CapPerUpgradeStar);
		std::printf("  the team's operators; a player without them can only make up the gap with skill.\n");
		std::printf("- Fights: the operators' damage, the enemies' danger order, crowd damage, uptime and dodging are assumptions of the fluid model in\n");
		std::printf("  `Tests/campaign_model.h` (reference team Luna, Plack, Kuu). The **threat** column below is the model's relative difficulty of a level,\n");
		std::printf("  Chapter 1 level 7 = 1.00; the section sizes of the generated levels were solved to hit the **target**. Nothing here was play-tested: the\n");
		std::printf("  owner's first play-through will say how the real fights compare.\n\n");

		std::printf("## Chapter 1 (the original eight level layouts, enemies scaled like every other chapter since 2026-10-06)\n\n");
		std::printf("| Level | Sections | Enemies | Mix | Recommended level | Health x | Damage x | Threat |\n|---|---:|---:|---|---:|---:|---:|---:|\n");
		for (int Level = 1; Level <= CampaignLevels; ++Level)
		{
			const int Stage = CampaignStageId(1, Level);
			const std::vector<FSectionPlanData> Plan = StagePlan(Stage);
			int Enemies = 0;
			for (const FSectionPlanData& S : Plan)
			{
				Enemies += S.Total();
			}
			const FEnemyScale& Scale = Solved.Tables.Scale[static_cast<size_t>(Stage)];
			std::printf("| 1-%d | %d | %d | %s | %d | %.2f | %.2f | %.2f |\n", Level, static_cast<int>(Plan.size()), Enemies, EnemyMixText(Plan).c_str(),
				Solved.Tables.Recommended[static_cast<size_t>(Stage)], Scale.Hp, Scale.Damage, Context.Threat(Stage, Plan));
		}

		for (int Chapter = FirstGeneratedChapter; Chapter <= CampaignChapters; ++Chapter)
		{
			std::printf("\n## Chapter %d - %s\n\n", Chapter, ChapterTheme(Chapter).c_str());
			if (Chapter == WalkChapter)
			{
				std::printf("Return to Nowhere (owner level idea, final): no levels, no bosses, no enemies, no rewards - one walk of about five\n"
					"minutes through `L_Ch11_ReturnToNowhere`; walking out clears the chapter (stage ids %d-%d). Nothing to grind; the team\n"
					"arrives at Chapter 12 at about level %d.\n", WalkEntryStage(), WalkLastStage(), Solved.Tables.Recommended[static_cast<size_t>(WalkLastStage())]);
				continue;
			}
			if (Solved.Tables.ChapterFactor[static_cast<size_t>(Chapter)] < 0.999)
			{
				std::printf("*Stat multipliers lowered by x%.2f: this chapter's enemy mix is more dangerous than the pace allows even at the smallest sections.*\n\n",
					Solved.Tables.ChapterFactor[static_cast<size_t>(Chapter)]);
			}
			std::printf("| Level | Sections x size | Enemies | Mix | Recommended level | Replays | Health x | Damage x | Threat | Target |\n|---|---|---:|---|---:|---:|---:|---:|---:|---:|\n");
			for (int Level = 1; Level <= CampaignLevels; ++Level)
			{
				const int Stage = CampaignStageId(Chapter, Level);
				const FSizeChoice& Choice = Solved.Sizes[static_cast<size_t>((Chapter - FirstGeneratedChapter) * CampaignLevels + (Level - 1))];
				const std::vector<FSectionPlanData> Plan = GeneratePlan(Chapter, Level, Choice.Size);
				int Enemies = 0;
				for (const FSectionPlanData& S : Plan)
				{
					Enemies += S.Total();
				}
				const FEnemyScale& Scale = Solved.Tables.Scale[static_cast<size_t>(Stage)];
				std::printf("| %d-%d%s | %d x %d | %d | %s | %d | %d | %.2f | %.2f | %.2f | %.2f |\n", Chapter, Level, Level == CampaignLevels ? " (boss)" : "",
					static_cast<int>(Plan.size()), Choice.Size, Enemies, EnemyMixText(Plan).c_str(), Solved.Tables.Recommended[static_cast<size_t>(Stage)],
					Solved.Tables.Pace[static_cast<size_t>(Stage)].Replays, Scale.Hp, Scale.Damage, Choice.Threat, Choice.Target);
			}
		}
		std::printf("\n## Regenerating\n\n`python3 Tools/gen_campaign_data.py` rebuilds `BIBRules/BIBCampaignData.inc` and this file. Change the reference player's\n");
		std::printf("assumptions in `Tests/campaign_model.h`, the rewards and archetypes in `BIBRules/BIBCampaign.*`, then rerun it and\n");
		std::printf("`Tests/run_core_tests.sh`.\n");
	}
}

int main(int ArgCount, char** Args)
{
	const FSolved Solved = SolveAll();
	if (ArgCount > 1 && std::strcmp(Args[1], "--md") == 0)
	{
		PrintMarkdown(Solved);
	}
	else
	{
		PrintInc(Solved);
	}
	return 0;
}

// stage rewards. Pure data and rules, no Unreal includes.
//
// Owner request 2026-10-05: fill the rest of the 13 chapters with levels made of standard balancing enemies — Basic
// (melee), Ranged, Mage (area damage), Brute (tank), Assassin (high damage, close range, low health), sub bosses (mini
// bosses) and bosses — a mini boss at the end of every level, and in a chapter's last level the mini boss in the stage
// (section) before the actual boss. Balance each stage to the currency, levels and operators a player has at that point
// of the game, a bit harder so that some grinding is needed.
//
// Everything numeric here is PLACEHOLDER: MAIN leaves enemy stats, level counts per chapter, rewards and rates OPEN or
// DEFERRED. The numbers are tuned against a reference player (docs/campaign.md); the owner replaces them.
//
// The tables in BIBCampaignData.inc are GENERATED by Tools/gen_campaign_data.py from the balance model in
// Tests/campaign_model.h. Do not edit that file by hand: change a constant, rerun the tool, run Tests/run_core_tests.sh.
#pragma once

#include <string>
#include <vector>

#include "BIBMeta.h"

namespace BIB
{
	namespace Campaign
	{
		// ------------------------------------------------------------------ enemy archetypes
		enum class EArchetype : int
		{
			Melee = 0,   // basic enemy
			Ranged,      // shoots from a distance
			Mage,        // telegraphed area blasts
			Brute,       // tank
			Assassin,    // fast, high damage, low health
			MiniBoss,    // sub boss, the end of every level
			Boss,        // main boss, the end of every chapter
			Count
		};
		constexpr int ArchetypeCount = static_cast<int>(EArchetype::Count);
		constexpr int RegularArchetypeCount = static_cast<int>(EArchetype::MiniBoss); // Melee..Assassin

		// How the balance model treats the attacks of an archetype.
		enum class EThreatGroup : int
		{
			Melee = 0,   // only a few can reach the operator at once
			Far,         // shoots or casts from range, all of them at once (part of the time)
			Rush,        // dashes in: always on the operator
			Boss         // one big target, telegraphed attacks
		};

		struct FArchetype
		{
			const char* Name;      // label over the enemy
			const char* Role;      // one line for the docs and the hub
			double Hp;             // base health, multiplied by the stage's Hp scale
			double Damage;         // damage of one attack, multiplied by the stage's Damage scale
			double Interval;       // seconds between attacks
			double Windup;         // telegraph before an attack lands
			double Speed;          // walking speed, cm/s
			double Range;          // reach of the attack from the enemy's centre in cm; 0 = melee (body radius + 130)
			double KeepMin;        // ranged and mage: backs off when the operator is closer than this (cm)
			double KeepMax;        // ranged and mage: approaches until the operator is this close (cm)
			double AoeRadius;      // 0 = single target; mage blasts hit everything inside this radius (cm)
			double Radius;         // capsule radius, cm
			double HalfHeight;     // capsule half height, cm
			int AbilityId;         // BIB::Kits::EnemyAbilities id (Adapt can copy it)
			double Avoid;          // balance model: share of the damage a skilled player avoids
			double Reach;          // balance model: share of the operator's damage that lands (ranged enemies are harder to reach)
			EThreatGroup Group;
			double SlamDamage;     // chapter boss only: telegraphed area slam (0 = none)
			double SlamInterval;
			double SlamWindup;
			double SlamRadius;
		};

		const FArchetype& Archetype(EArchetype Kind);
		const char* ArchetypeName(EArchetype Kind);

		// ---------------------------------------------------------------------- level plans
		// Chapter 1 keeps its original plan table (BIBMeta.cpp). Chapters 2-13 are generated: every level has 2-5 sections of
		// 10-30 enemies, a mini boss at the end of the last section, and a chapter's last level puts the mini boss in the
		// section before the boss. Each archetype is introduced chapter by chapter: Ranged in 2, Mages in 3, Assassins in 4;
		// from chapter 5 every chapter leans on one or two of them (a PLACEHOLDER theme, no lore).
		constexpr int FirstGeneratedChapter = 2;
		constexpr int MinSectionSize = 10;   // MAIN section 7: 10-30 enemies per section
		constexpr int MaxSectionSize = 30;
		constexpr int MinSections = 2;       // MAIN section 7: 2-5 sections per level
		constexpr int MaxSections = 5;

		int SectionsInLevel(int Chapter, int Level);                 // chapters 2-13; 2..5
		double ArchetypeWeight(int Chapter, EArchetype Kind);        // share of the regular enemies, 0 when not introduced (Melee..Assassin)
		bool IsIntroduced(int Chapter, EArchetype Kind);
		std::string ChapterTheme(int Chapter);                       // e.g. "Ranged enemies join the fight"
		// The plan for a chapter's level with every section of SectionSize enemies (mini boss / boss sections included).
		std::vector<FSectionPlanData> GeneratePlan(int Chapter, int Level, int SectionSize);
		int SectionSizeFor(int Chapter, int Level);                  // the generated table value used by the shipped plans
		std::vector<FSectionPlanData> ChapterPlan(int Chapter, int Level);   // GeneratePlan with the table size
		// "10 basic, 4 ranged, 2 brutes, 1 mini-boss" for a whole plan (hub text).
		std::string EnemyMixText(const std::vector<FSectionPlanData>& Plan);
		// The count of one archetype in a section.
		int CountOf(const FSectionPlanData& Section, EArchetype Kind);

		// ---------------------------------------------------------------- scaling and rewards
		// Every stage, Chapter 1 included (owner rebalance 2026-10-06), follows the reference player (see docs/campaign.md):
		// health tracks the damage a player with the expected levels deals, damage tracks the health they have, so the much
		// steeper per-level growth of the operators (Config::StatPercentPerLevel) is matched by the enemies.
		FEnemyScale CampaignScales(int GlobalLevel);
		// The team level (average of the three operators) a player is expected to bring to this stage: the level a player who
		// clears every stage and replays about once per stage has reached. The Campaign page shows it as a hint.
		int RecommendedLevel(int GlobalLevel);

		struct FStageReward
		{
			int Gold = 0;
			int Bytes = 0;
			int Hearts = 0;
			int Diamonds = 0;   // first clear only
		};
		// Gold, Bytes and Angel hearts are paid on every clear (that is what grinding means); Diamonds on the first clear only.
		// Owner request 2026-10-06: Chapter 1 level 1 pays 800 Gold, 250 Bytes and 2 Angel hearts per clear and 50 Diamonds on the
		// first clear; later levels and the boss levels are balanced from there (the curve below is PLACEHOLDER). Tickets are no
		// longer a stage reward: they come from the chapter quests (BIBMetaOps.h, StoryQuest).
		FStageReward StageReward(int GlobalLevel);
		FStageReward CurveReward(int GlobalLevel);   // the reward curve itself (StageReward minus the Chapter 11 walk); story quests use it
		bool IsBossStage(int GlobalLevel);   // a chapter's last level (the chapter boss)

		// Owner level idea (final, 2026-10-07): Chapter 11 "Return to Nowhere" has no levels, no bosses, nothing - one walk of about
		// five minutes through L_Ch11_ReturnToNowhere, then you walk out. Its eight stage ids stay (saves and numbering unchanged):
		// the first one is the walk, walking out clears the whole chapter, and none of them has enemies or pays rewards (2026-10-09).
		constexpr int WalkChapter = 11;
		bool IsWalkStage(int GlobalLevel);   // any stage id of Chapter 11
		int WalkEntryStage();                // its first stage id: the walk
		int WalkLastStage();                 // its last stage id (cleared by the walk)

		// ------------------------------------------------------------ constants shared with the balance model
		constexpr int RewardGoldBase = 800;           // owner: stage 1 Gold per clear
		constexpr int RewardBytesBase = 250;          // owner: stage 1 Bytes per clear
		constexpr int RewardHeartsBase = 2;           // owner: stage 1 Angel hearts per clear
		constexpr int RewardDiamondsBase = 50;        // owner: stage 1 Diamonds, first clear only
		constexpr double RewardGrowthPerStage = 0.12; // PLACEHOLDER: Gold and Bytes grow by 12% of the stage-1 amount per stage
		constexpr double RewardHeartsGrowthPerStage = 0.06; // PLACEHOLDER: hearts grow at half that pace (the gates need few; spare hearts trade for Gold)
		constexpr int RewardDiamondsPerChapter = 10;  // PLACEHOLDER: +10 first-clear Diamonds per chapter (50, 60, ... 170)
		constexpr double RewardBossMultiplier = 2.0;  // PLACEHOLDER: a boss level pays twice the Gold, Bytes and hearts of its curve ...
		constexpr int RewardBossDiamondsMultiplier = 3; // ... and three times the first-clear Diamonds
	}
}

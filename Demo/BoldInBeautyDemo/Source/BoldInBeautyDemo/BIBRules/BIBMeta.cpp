	// ================================================================= stages
	int CampaignStageId(int Level)
	{
		return CampaignStageId(1, Level);
	}

	int CampaignStageId(int Chapter, int Level)
	{
		return (Chapter - 1) * CampaignLevels + Level;
	}

	int ChapterOfStage(int CampaignStage)
	{
		return CampaignStage >= 1 && CampaignStage <= TotalCampaignLevels ? (CampaignStage - 1) / CampaignLevels + 1 : 0;
	}

	int LevelOfStage(int CampaignStage)
	{
		return CampaignStage >= 1 && CampaignStage <= TotalCampaignLevels ? (CampaignStage - 1) % CampaignLevels + 1 : 0;
	}

	int ChapterFirstStage(int Chapter)
	{
		return CampaignStageId(Chapter, 1);
	}

	int TowerStageId(int Mode, int Floor)
	{
		// Endless (owner request 2026-10-06): one million floors per mode fit in an int stage id.
		return 1000000 * (Mode + 1) + Floor;
	}

	int SubStoryStageId(int Story, int Level)
	{
		return 3000 + Story * 10 + Level;
	}

	FStageRef DecodeStage(int StageId)
	{
		FStageRef Ref;
		if (StageId >= Arcade::BossRushStageBase)
		{
			Ref.Kind = EStageKind::BossRush;
			Ref.A = Arcade::BossRushBaseOf(StageId);
			Ref.B = Arcade::BossRushRoundOf(StageId);
		}
		else if (StageId >= 1000000)
		{
			Ref.Kind = EStageKind::Tower;
			Ref.A = StageId / 1000000 - 1;
			Ref.B = StageId % 1000000;
		}
		else if (StageId >= 3000)
		{
			Ref.Kind = EStageKind::SubStory;
			Ref.A = (StageId - 3000) / 10;
			Ref.B = (StageId - 3000) % 10;
		}
		else
		{
			Ref.Kind = EStageKind::Campaign;
			Ref.A = std::max(1, ChapterOfStage(StageId));
			Ref.B = std::max(1, LevelOfStage(StageId));
		}
		return Ref;
	}

	int SubStoryLevels(int Story)
	{
		static const int Levels[SubStoryCount] = {3, 2, 1, 2};
		return Story >= 0 && Story < SubStoryCount ? Levels[Story] : 0;
	}

	std::string SubStoryTitle(int Story)
	{
		static const char* Letters[SubStoryCount] = {"A", "B", "C", "D"};
		return Story >= 0 && Story < SubStoryCount ? std::string("Sub-story ") + Letters[Story] + " (placeholder title)" : "?";
	}

	bool IsValidStage(int StageId)
	{
		const FStageRef Ref = DecodeStage(StageId);
		switch (Ref.Kind)
		{
		case EStageKind::Campaign: return StageId >= 1 && StageId <= TotalCampaignLevels;
		case EStageKind::Tower: return (Ref.A == 0 || Ref.A == 1) && Ref.B >= 1 && Ref.B <= MaxTowerFloor;
		case EStageKind::SubStory: return StageId < 3000 + SubStoryCount * 10 && Ref.A >= 0 && Ref.A < SubStoryCount && Ref.B >= 1 && Ref.B <= SubStoryLevels(Ref.A);
		case EStageKind::BossRush: return Ref.A >= 1 && Ref.A <= TotalCampaignLevels && Ref.B >= 1 && Ref.B <= Arcade::BossRushMaxRound;
		}
		return false;
	}

	std::string StageName(int StageId)
	{
		const FStageRef Ref = DecodeStage(StageId);
		switch (Ref.Kind)
		{
		case EStageKind::Campaign:
			if (Campaign::IsWalkStage(StageId))
			{
				return "Chapter " + std::to_string(Ref.A) + " - Return to Nowhere";   // owner's chapter title; a single walk
			}
			return "Chapter " + std::to_string(Ref.A) + " - Level " + std::to_string(Ref.B) + (Ref.B >= CampaignLevels ? " (chapter end)" : "");
		case EStageKind::Tower:
			return std::string("The Ark Tower - ") + (Ref.A == 0 ? "Operator" : "Secrets") + " mode, floor " + std::to_string(Ref.B);
		case EStageKind::SubStory:
			return SubStoryTitle(Ref.A) + " - level " + std::to_string(Ref.B);
		case EStageKind::BossRush:
			return "Boss Rush - round " + std::to_string(Ref.B);
		}
		return "?";
	}

	bool IsChapterFinal(int StageId)
	{
		const FStageRef Ref = DecodeStage(StageId);
		return Ref.Kind == EStageKind::Campaign && StageId >= 1 && StageId <= TotalCampaignLevels && Ref.B >= CampaignLevels;
	}

	std::vector<FSectionPlanData> StagePlan(int StageId)
	{
		// MAIN §7: 2-5 sections per stage, 10-30 enemies per section, a mini-boss every stage, a boss only at the
		// chapter end. Chapter 1 is the table below (PLACEHOLDER compositions, repeated in Tools/build_assets.py for the
		// editor maps); chapters 2-13 are generated by BIBCampaign.cpp.
		struct Row
		{
			int Grunts, Brutes, Mini, Boss;
		};
		static const std::vector<std::vector<Row>> Chapter1 = {
			{{10, 0, 0, 0}, {9, 3, 1, 0}},
			{{12, 2, 0, 0}, {10, 4, 1, 0}},
			{{12, 4, 0, 0}, {10, 4, 0, 0}, {8, 4, 1, 0}},
			{{14, 4, 0, 0}, {12, 6, 0, 0}, {10, 6, 1, 0}},
			{{14, 6, 0, 0}, {12, 6, 0, 0}, {10, 8, 1, 0}},
			{{16, 6, 0, 0}, {14, 6, 0, 0}, {12, 8, 0, 0}, {10, 8, 1, 0}},
			{{16, 8, 0, 0}, {14, 8, 0, 0}, {12, 10, 0, 0}, {12, 10, 1, 0}},
			{{14, 6, 0, 0}, {14, 8, 0, 0}, {12, 10, 0, 0}, {10, 10, 0, 0}, {8, 6, 1, 1}},
		};
		std::vector<FSectionPlanData> Plan;
		if (!IsValidStage(StageId))
		{
			return Plan;
		}
		const FStageRef Ref = DecodeStage(StageId);
		auto Push = [&Plan](int Grunts, int Brutes, int Mini, int Boss)
		{
			FSectionPlanData Section;
			Section.Grunts = Grunts;
			Section.Brutes = Brutes;
			Section.MiniBosses = Mini;
			Section.Bosses = Boss;
			Plan.push_back(Section);
		};
		switch (Ref.Kind)
		{
		case EStageKind::Campaign:
			if (Ref.A == 1)
			{
				for (const Row& Entry : Chapter1[static_cast<size_t>(Ref.B - 1)])
				{
					Push(Entry.Grunts, Entry.Brutes, Entry.Mini, Entry.Boss);
				}
			}
			else
			{
				Plan = Campaign::ChapterPlan(Ref.A, Ref.B);
			}
			break;
		case EStageKind::Tower:
			// One section per floor, endless; a mini-boss every fifth floor and a boss every 25th.
			Push(std::min(18, 10 + Ref.B / 2), std::min(10, Ref.B / 3), Ref.B % 5 == 0 ? 1 : 0, Ref.B % 25 == 0 ? 1 : 0);
			break;
		case EStageKind::BossRush:
			// One arena; BIBGameMode refills it with the next round's bosses (Arcade::BossRushRound).
			Plan.push_back(Arcade::BossRushRound(Ref.B));
			break;
		case EStageKind::SubStory:
			// Short chapters: two small sections, a mini-boss on the last.
			Push(10, 1 + Ref.B, 0, 0);
			Push(10 + Ref.B, 2 + Ref.B, 1, 0);
			break;
		}
		return Plan;
	}

	FEnemyScale StageScales(int StageId)
	{
		const FStageRef Ref = DecodeStage(StageId);
		FEnemyScale Scale;
		switch (Ref.Kind)
		{
		case EStageKind::Campaign: return Campaign::CampaignScales(StageId);
		case EStageKind::Tower:
			// +6% a floor, the same as an operator level (PLACEHOLDER); Secrets mode (5-6* operators) is 30% tougher. Balancing pass
			// 2026-10-09: the floors also ramp to the campaign's 1.5x hardness over the first eight floors (like Chapter 1). Without it a
			// floor was as easy as a campaign stage about 1.5x its number, so the first-clear rewards a player could collect at their
			// campaign difficulty were about three times the campaign's own (2.3M Gold vs 0.7M by the end) and skipped the Charge pace.
			Scale.Hp = (1.0 + 0.06 * (Ref.B - 1)) * (1.0 + 0.5 * std::min(1.0, (Ref.B - 1) / 7.0)) * (Ref.A == 1 ? 1.3 : 1.0);
			break;
		case EStageKind::BossRush: return Arcade::BossRushScales(StageId);
		case EStageKind::SubStory: Scale.Hp = 1.0 + 0.1 * Ref.A; break;
		}
		Scale.Damage = Scale.Hp;
		return Scale;
	}

	double StageEnemyScale(int StageId)
	{
		return StageScales(StageId).Hp;
	}


	// ============================================================== meta state
	static FMail MakeMail(FMeta& Meta, const char* Title, const char* Body, const FReward& Reward)
	{
		FMail Mail;
		Mail.Id = Meta.NextMailId++;
		Mail.Title = Title;
		Mail.Body = Body;
		Mail.Reward = Reward;
		return Mail;
	}

	FMeta MakeNewMeta()
	{
		FMeta Meta;
		Meta.Daily.assign(static_cast<size_t>(DailyQuestCount), FQuestProgress());
		Meta.Weekly.assign(static_cast<size_t>(WeeklyQuestCount), FQuestProgress());
		Meta.Story.assign(static_cast<size_t>(StoryQuestCount), FQuestProgress());
		Meta.Milestones.assign(static_cast<size_t>(MilestoneCount), FQuestProgress());
		// Owner request 2026-10-06: "make no beginning mail appear" - a new mailbox is empty (it used to hold three placeholder letters).
		return Meta;
	}

	void ResetDaily(FMeta& Meta, int NewDay)
	{
		for (FQuestProgress& Quest : Meta.Daily)
		{
			Quest = FQuestProgress();
		}
		// Weekly quests reset when the day enters a new 7-day week.
		const int Week = (std::max(1, NewDay) - 1) / 7;
		if (Week != Meta.WeekIndex)
		{
			Meta.WeekIndex = Week;
			for (FQuestProgress& Quest : Meta.Weekly)
			{
				Quest = FQuestProgress();
			}
		}
		Meta.ArenaAttempts = 5;
		Meta.ChargeRefillsToday = 0;
		// Monthly supply (simulated purchase, BIBInventory.h): 100 Diamonds by mail every day while it lasts.
		if (Meta.MonthlyDays > 0)
		{
			--Meta.MonthlyDays;
			FReward Monthly;
			Monthly.Diamonds = 100;
			Meta.Mail.push_back(MakeMail(Meta, "Monthly supply", ("100 Diamonds - " + std::to_string(Meta.MonthlyDays) + " days left.").c_str(), Monthly));
		}
		FReward Supply;
		Supply.Gold = 500;   // rescaled 2026-10-06 to the new stage economy (PLACEHOLDER)
		Supply.Bytes = 150;
		Meta.Mail.push_back(MakeMail(Meta, ("Day " + std::to_string(NewDay) + " daily supply").c_str(), "Placeholder daily gift.", Supply));
		while (Meta.Mail.size() > 20)
		{
			auto Oldest = std::find_if(Meta.Mail.begin(), Meta.Mail.end(), [](const FMail& Mail) { return Mail.bClaimed; });
			Meta.Mail.erase(Oldest == Meta.Mail.end() ? Meta.Mail.begin() : Oldest);
		}
	}
